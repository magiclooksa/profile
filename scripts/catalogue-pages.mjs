// Writes one HTML page per project catalogue, and the index the profile reads.
//
//   node scripts/catalogue-pages.mjs
//
// Each project's data lives in public/data/projects/<slug>.json (the same shape as villa-wood.json).
// Its page, <slug>.html at the root, is villa-wood.html with the project's own cover, titles and
// description written in, so the cover shows before any script runs and link previews read it.
// The index, public/data/catalogues.json, lists every catalogue (the villa first) for the profile.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const projectsDir = path.join(root, 'public/data/projects');
const template = read('villa-wood.html');
const villa = JSON.parse(read('public/data/villa-wood.json'));

const escape = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const titleCase = (s) => s.toLowerCase().replace(/(^|\s)\S/g, (c) => c.toUpperCase());

/** Swaps one exact piece of the template, and fails loudly if the template has changed. */
function swap(html, from, to) {
  if (!html.includes(from)) throw new Error(`villa-wood.html no longer contains: ${from}`);
  return html.split(from).join(to);
}

function page(slug, p) {
  let html = template;
  const description = `${p.name.ar}: ${p.tagline}`;
  html = swap(html, '<meta name="description" content="كتالوج تفصيلي لفيلا الخشب من النظرة الساحرة: المساحات والقطع والخامات." />',
    `<meta name="description" content="${escape(description)}" />`);
  html = swap(html, '<title>فيلا الخشب | النظرة الساحرة</title>', `<title>${escape(p.name.ar)} | النظرة الساحرة</title>`);
  html = swap(html, './images/villa/living-wide-b.webp', `./${p.cover.src}`);
  html = swap(html, 'alt="الصالة العائلية في فيلا الخشب: جدار من البلوط وثريا من الجوت فوق الجلسة"', `alt="${escape(p.cover.caption)}"`);
  html = swap(html, '<body class="villa-body">', `<body class="villa-body" data-catalogue="projects/${slug}.json">`);
  html = swap(html, '<p class="vbar-title"><span>فيلا الخشب</span>', `<p class="vbar-title"><span>${escape(p.name.ar)}</span>`);
  html = swap(html, '<p class="vcover-kicker">كتالوج التصميم الداخلي والأثاث</p>', `<p class="vcover-kicker">${escape(p.kicker)}</p>`);
  html = swap(html, '<h1 class="vcover-title" id="cover-title">فيلا الخشب</h1>', `<h1 class="vcover-title${[...p.name.ar].length > 12 ? ' is-long' : ''}" id="cover-title">${escape(p.name.ar)}</h1>`);
  html = swap(html, '<p class="vcover-en latin">The Wood Villa</p>', `<p class="vcover-en latin">${escape(titleCase(p.name.en))}</p>`);
  html = swap(html, '<p class="vcover-tag">بلوط دافئ، وترافرتين هادئ، وكتان يتنفّس ضوء النهار.</p>', `<p class="vcover-tag">${escape(p.tagline)}</p>`);
  return `<!-- Generated by scripts/catalogue-pages.mjs from villa-wood.html. Edit the template or public/data/projects/${slug}.json, not this file. -->\n${html}`;
}

const entry = (href, p) => ({
  href,
  name: p.name,
  place: p.place,
  kicker: p.kicker,
  tagline: p.tagline,
  cover: p.cover,
  spaces: p.spaces.length,
  pieces: p.products.length,
  materials: p.materials.length,
  film: p.film !== null,
  // Three photos fanned out on the card like catalogue pages: a material, a piece and a room.
  pages: [
    { src: p.materials[0].swatch, caption: 'الخامات' },
    { src: p.products[0].card, caption: p.products[0].name },
    { src: p.intro.image.src, caption: p.spaces[0].name },
  ],
});

const index = [entry('villa-wood.html', villa)];
const slugs = fs.existsSync(projectsDir)
  ? fs.readdirSync(projectsDir).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort()
  : [];
for (const slug of slugs) {
  const p = JSON.parse(fs.readFileSync(path.join(projectsDir, `${slug}.json`), 'utf8'));
  fs.writeFileSync(path.join(root, `${slug}.html`), page(slug, p));
  index.push(entry(`${slug}.html`, p));
}
fs.writeFileSync(path.join(root, 'public/data/catalogues.json'), `${JSON.stringify(index, null, 2)}\n`);
console.log(`${slugs.length} project pages, ${index.length} catalogues in the index`);
